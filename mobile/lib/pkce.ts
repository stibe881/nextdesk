/**
 * Dependency-free PKCE helpers for the native SSO start.
 *
 * The SHA-256 implementation is intentionally synchronous and pure JavaScript:
 * the native sign-in start must never wait on a platform crypto promise. Only
 * the random verifier bytes come from the operating system's CSPRNG.
 */

